/* Optional Claude backend for the AI features. The apps work fully without it
   (local retrieval / rule-based insights). When the user adds an API key in
   Settings, answers are generated by the Claude Messages API directly from the browser. */
(function () {
  'use strict';

  const ENDPOINT = 'https://api.anthropic.com/v1/messages';
  const DEFAULT_MODEL = 'claude-sonnet-5-5';

  /** Returns the assistant's text. Throws an Error with a readable message on failure. */
  async function ask({ apiKey, model = DEFAULT_MODEL, system, prompt, maxTokens = 900 }) {
    if (!apiKey) throw new Error('No API key set. Add one in Settings.');
    let res;
    try {
      res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'x-api-key': apiKey,
          'anthropic-version': '2023-06-01',
          'anthropic-dangerous-direct-browser-access': 'true',
        },
        body: JSON.stringify({
          model,
          max_tokens: maxTokens,
          system,
          messages: [{ role: 'user', content: prompt }],
        }),
      });
    } catch (_) {
      throw new Error('Network error. Check your connection and try again.');
    }
    if (!res.ok) {
      let message = `Request failed (HTTP ${res.status}).`;
      try {
        const body = await res.json();
        if (body && body.error && body.error.message) message = body.error.message;
      } catch (_) { /* keep default message */ }
      throw new Error(message);
    }
    const data = await res.json();
    return (data.content || []).filter((block) => block.type === 'text').map((block) => block.text).join('\n').trim();
  }

  window.AI = { ask, DEFAULT_MODEL };
})();
